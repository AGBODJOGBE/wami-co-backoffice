const REF = (city: string, n: number) =>
  `B2B-${city.slice(0, 3).toUpperCase()}-2026-${String(n).padStart(4, "0")}`;

function shipment(
  i: number,
  patch: Partial<Shipment> & {
    status: Shipment["status"];
    sender: Sender;
    courier?: Courier;
    pickup?: string;
    drop?: string;
  },
): Shipment {
  const senderName = patch.sender.name;
  const senderId = patch.sender.id;
  const pickupCity = patch.sender.city;
  const dropCity = patch.drop ?? "Calavi";
  const pickupAt =
    patch.pickupAt ??
    new Date(Date.now() - i * 1000 * 60 * 18).toISOString();
  const expectedDropoffAt = new Date(
    new Date(pickupAt).getTime() + 60 * 60 * 1000,
  ).toISOString();
  return {
    id: `sh-${String(i).padStart(4, "0")}`,
    reference: REF(pickupCity, i + 489),
    status: patch.status,
    priority: patch.priority ?? "STANDARD",
    category: patch.category ?? "DOCUMENTS",
    weightKg: patch.weightKg ?? 1.5,
    declaredValue: patch.declaredValue ?? 25_000,
    pickup: {
      label: senderName,
      city: pickupCity,
      district: patch.pickup ?? "Ganhi",
      contactName: patch.sender.contactName,
      contactPhone: patch.sender.contactPhone,
    },
    dropoff: {
      label: patch.drop ?? "Client final",
      city: dropCity,
      district: "Centre",
      contactName: "Récipiendaire",
      contactPhone: "+229 0162 00 00 00",
    },
    distanceKm: patch.distanceKm ?? 8.4,
    pickupAt,
    expectedDropoffAt,
    deliveredAt:
      patch.status === "DELIVERED"
        ? new Date(
            new Date(expectedDropoffAt).getTime() - 1000 * 60 * 7,
          ).toISOString()
        : null,
    senderId,
    senderName,
    courierId: patch.courier?.id ?? null,
    courierName: patch.courier?.fullName ?? null,
    vehicle: patch.courier?.primaryVehicle ?? null,
    price: patch.price ?? 2_400,
    paymentMethod: patch.paymentMethod ?? "INVOICE",
    notes: patch.notes,
    timeline: patch.timeline ?? buildTimeline(patch.status, pickupAt),
  };
}

function buildTimeline(
  status: Shipment["status"],
  pickupAtIso: string,
): Shipment["timeline"] {
  const t0 = new Date(pickupAtIso).getTime();
  const evts: Shipment["timeline"] = [];
  evts.push({
    at: new Date(t0 - 1000 * 60 * 30).toISOString(),
    label: "Commande créée",
    by: "Sender app",
    kind: "info",
  });
  if (status === "DRAFT") return evts;
  evts.push({
    at: new Date(t0 - 1000 * 60 * 20).toISOString(),
    label: "Validée — en attente d'un livreur",
    kind: "info",
  });
  if (status === "PENDING_PICKUP") return evts;
  evts.push({
    at: new Date(t0 - 1000 * 60 * 10).toISOString(),
    label: "Livreur assigné",
    by: "Algo dispatch",
    kind: "info",
  });
  if (status === "ASSIGNED") return evts;
  evts.push({
    at: new Date(t0).toISOString(),
    label: "Colis collecté chez l'expéditeur",
    by: "Sandra Adoumon",
    kind: "success",
  });
  if (status === "PICKED_UP") return evts;
  evts.push({
    at: new Date(t0 + 1000 * 60 * 5).toISOString(),
    label: "En transit",
    kind: "info",
  });
  if (status === "IN_TRANSIT") return evts;
  if (status === "DELIVERED") {
    evts.push({
      at: new Date(t0 + 1000 * 60 * 53).toISOString(),
      label: "Livré au destinataire (signature OK)",
      by: "Sandra Adoumon",
      kind: "success",
    });
  }
  if (status === "FAILED") {
    evts.push({
      at: new Date(t0 + 1000 * 60 * 35).toISOString(),
      label: "Échec : destinataire absent",
      kind: "danger",
    });
  }
  if (status === "CANCELLED") {
    evts.push({
      at: new Date(t0 + 1000 * 60 * 12).toISOString(),
      label: "Annulée par l'expéditeur",
      kind: "warning",
    });
  }
  return evts;
}

